CREATE TABLE shopping_search_quota_locks (
    owner_id VARCHAR(120) PRIMARY KEY
);

CREATE TABLE shopping_search_request_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id VARCHAR(120) NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX shopping_search_request_events_owner_time_idx
    ON shopping_search_request_events (owner_id, requested_at);
