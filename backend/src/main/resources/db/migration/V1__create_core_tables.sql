CREATE TABLE spending_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id VARCHAR(120) NOT NULL UNIQUE,
    max_per_product NUMERIC(12, 2) NOT NULL CHECK (max_per_product > 0),
    max_per_order NUMERIC(12, 2) NOT NULL CHECK (max_per_order > 0),
    weekly_limit NUMERIC(12, 2) NOT NULL CHECK (weekly_limit > 0),
    max_orders_per_week INTEGER NOT NULL CHECK (max_orders_per_week > 0),
    currency CHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    country CHAR(2) NOT NULL CHECK (country ~ '^[A-Z]{2}$'),
    hard_limits_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (max_per_product <= max_per_order),
    CHECK (max_per_order <= weekly_limit)
);

CREATE TABLE payment_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id VARCHAR(120) NOT NULL,
    product_id VARCHAR(200) NOT NULL,
    product_name VARCHAR(500) NOT NULL,
    merchant_name VARCHAR(200),
    retailer_offer_url TEXT,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    currency CHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    status VARCHAR(20) NOT NULL CHECK (status IN ('CREATED', 'APPROVED', 'COMPLETED', 'CANCELLED', 'FAILED')),
    idempotency_key VARCHAR(100) NOT NULL UNIQUE,
    paypal_order_id VARCHAR(100) UNIQUE,
    paypal_capture_id VARCHAR(100) UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    CHECK ((status = 'COMPLETED') = (paypal_capture_id IS NOT NULL)),
    CHECK ((status = 'COMPLETED') = (completed_at IS NOT NULL))
);

CREATE INDEX payment_transactions_owner_created_idx
    ON payment_transactions (owner_id, created_at DESC);

CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id VARCHAR(120),
    event_type VARCHAR(100) NOT NULL,
    request_id VARCHAR(100),
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX audit_events_created_idx ON audit_events (created_at DESC);

